import { use, useState } from 'react';
import {
  Box,
  BoxProps,
  createVarsResolver,
  getRadius,
  getSize,
  MantineColor,
  MantineGradient,
  MantineRadius,
  MantineSize,
  polymorphicFactory,
  PolymorphicFactory,
  StylesApiProps,
  useProps,
  useStyles,
} from '../../core';
import {
  AvatarGroup,
  type AvatarGroupCssVariables,
  type AvatarGroupFactory,
  type AvatarGroupProps,
  type AvatarGroupStylesNames,
} from './AvatarGroup/AvatarGroup';
import {
  AvatarGroupContext,
  type AvatarGroupContextValue,
} from './AvatarGroup/AvatarGroup.context';
import { AvatarPlaceholderIcon } from './AvatarPlaceholderIcon';
import { getInitialsColor } from './get-initials-color/get-initials-color';
import { getInitials } from './get-initials/get-initials';
import classes from './Avatar.module.css';
export type AvatarStylesNames = 'root' | 'placeholder' | 'image';
export type AvatarVariant =
  | 'filled'
  | 'light'
  | 'gradient'
  | 'outline'
  | 'transparent'
  | 'default'
  | 'white';

export type AvatarCssVariables = {
  root: '--avatar-size' | '--avatar-radius' | '--avatar-bg' | '--avatar-color' | '--avatar-bd';
};

export interface AvatarProps extends BoxProps, StylesApiProps<AvatarFactory> {
  /** Width and height of the avatar, numbers are converted to rem @default 'md' @category appearance */
  size?: MantineSize | (string & {}) | number;

  /** Key of `theme.radius` or any valid CSS value to set border-radius @default '1000px' @category appearance */
  radius?: MantineRadius;

  /** Key of `theme.colors` or any valid CSS color @default 'gray' @category appearance */
  color?: MantineColor | 'initials';

  /** Gradient configuration for `variant="gradient"` @default theme.defaultGradient @category appearance */
  gradient?: MantineGradient;

  /** Image url, if the image cannot be loaded or `src={null}`, then placeholder is displayed instead @category appearance */
  src?: string | null;

  /** Image `alt` attribute, also used as `title` attribute for placeholder @category accessibility */
  alt?: string;

  /** Attributes passed down to `img` element */
  imageProps?: React.ComponentProps<'img'>;

  /** Avatar placeholder, displayed when `src={null}` or when the image cannot be loaded @category appearance */
  children?: React.ReactNode;

  /** If set, adjusts text color based on background color for `filled` variant @category appearance */
  autoContrast?: boolean;

  /** Name of the user. When `src` is not set, used to display initials and to generate color when `color="initials"` is set. @category appearance */
  name?: string;

  /** A list of colors that is used for autogenerated initials. By default, all default Mantine colors can be used except gray and dark. @category appearance */
  allowedInitialsColors?: MantineColor[];
}

export type AvatarFactory = PolymorphicFactory<{
  props: AvatarProps;
  defaultRef: HTMLDivElement;
  defaultComponent: 'div';
  stylesNames: AvatarStylesNames;
  vars: AvatarCssVariables;
  variant: AvatarVariant;
  staticComponents: {
    Group: typeof AvatarGroup;
  };
}>;

const varsResolver = createVarsResolver<AvatarFactory>(
  (
    theme,
    { size, radius, variant, gradient, color, autoContrast, name, allowedInitialsColors }
  ) => {
    const _color =
      color === 'initials' && typeof name === 'string'
        ? getInitialsColor(name, allowedInitialsColors)
        : color;

    const colors = theme.variantColorResolver({
      color: _color || 'gray',
      theme,
      gradient,
      variant: variant || 'light',
      autoContrast,
    });

    return {
      root: {
        '--avatar-size': getSize(size, 'avatar-size'),
        '--avatar-radius': radius === undefined ? undefined : getRadius(radius),
        '--avatar-bg': _color || variant ? colors.background : undefined,
        '--avatar-color': _color || variant ? colors.color : undefined,
        '--avatar-bd': _color || variant ? colors.border : undefined,
      },
    };
  }
);

export const Avatar = polymorphicFactory<AvatarFactory>((_props) => {
  const props = useProps('Avatar', null, _props);
  const {
    classNames,
    className,
    style,
    styles,
    unstyled,
    vars,
    src,
    alt,
    radius,
    color,
    gradient,
    imageProps,
    children,
    autoContrast,
    mod,
    name,
    allowedInitialsColors,
    attributes,
    ...others
  } = props;
  const groupCtx = use(AvatarGroupContext);
  const [{ src: loadedSrc, error }, setImageState] = useState({ src, error: !src });

  if (src !== loadedSrc) {
    setImageState({ src, error: !src });
  }

  const getStyles = useStyles<AvatarFactory>({
    name: 'Avatar',
    props,
    classes,
    className,
    style,
    classNames,
    styles,
    unstyled,
    attributes,
    vars,
    varsResolver,
  });

  return (
    <Box {...getStyles('root')} mod={[{ 'within-group': groupCtx.withinGroup }, mod]} {...others}>
      {error || !src ? (
        <span {...getStyles('placeholder')} title={alt ?? name}>
          {children || (typeof name === 'string' && getInitials(name)) || <AvatarPlaceholderIcon />}
        </span>
      ) : (
        <img
          {...imageProps}
          {...getStyles('image')}
          src={src}
          alt={alt ?? ''}
          onError={(event) => {
            setImageState({ src, error: true });
            imageProps?.onError?.(event);
          }}
        />
      )}
    </Box>
  );
});

Avatar.classes = classes;
Avatar.varsResolver = varsResolver;
Avatar.displayName = '@mantine/core/Avatar';

// AvatarGroup renders Avatar for its overflow counter, so the two modules import each other.
// Reading the AvatarGroup binding here at module evaluation time throws when AvatarGroup is
// evaluated first (`Cannot access 'AvatarGroup' before initialization`), so the read is deferred
// to the first Avatar.Group access instead.
Object.defineProperty(Avatar, 'Group', {
  configurable: true,
  enumerable: true,
  get: () => AvatarGroup,
});

export namespace Avatar {
  export type Props = AvatarProps;
  export type StylesNames = AvatarStylesNames;
  export type CssVariables = AvatarCssVariables;
  export type Variant = AvatarVariant;
  export type Factory = AvatarFactory;

  export namespace Group {
    export type Props = AvatarGroupProps;
    export type StylesNames = AvatarGroupStylesNames;
    export type CssVariables = AvatarGroupCssVariables;
    export type Factory = AvatarGroupFactory;
    export type ContextValue = AvatarGroupContextValue;
  }
}
